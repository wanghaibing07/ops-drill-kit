#!/usr/bin/env python3
"""Generate the exercise results page from the protected event stream."""
import argparse
import fcntl
import os
from pathlib import Path
import stat
import subprocess
import sys
import tempfile

PROJECT=Path(__file__).resolve().parent.parent
EVENTS=Path('/var/lib/opsdrill/events.jsonl')
RESULT=PROJECT/'docs/results.md'
HISTORY=PROJECT/'docs/results-m02-history.md'
MARKER='<!-- generated by scripts/export_results.py; do not edit by hand -->\n'


def render():
    fd=os.open(EVENTS,os.O_RDONLY|os.O_NOFOLLOW|os.O_CLOEXEC)
    try:
        st=os.fstat(fd)
        if not stat.S_ISREG(st.st_mode) or st.st_uid!=0 or st.st_nlink!=1 or stat.S_IMODE(st.st_mode)!=0o600:
            raise RuntimeError('event stream is not protected')
        fcntl.flock(fd,fcntl.LOCK_SH)
        cp=subprocess.run([sys.executable,'-B',str(PROJECT/'scripts/report.py'),'--markdown'],
                          capture_output=True,text=True,check=True,timeout=30)
        if not cp.stdout.startswith('# 演练结果\n'):
            raise RuntimeError('report output not recognized')
        return MARKER+cp.stdout
    finally:os.close(fd)


def write_result(text,adopt_existing=False):
    if not text.startswith(MARKER):raise RuntimeError('invalid generated output')
    directory=RESULT.parent
    if directory.is_symlink() or not directory.is_dir():raise RuntimeError('unsafe results directory')
    owner=directory.stat()
    if os.path.lexists(RESULT):
        st=RESULT.lstat()
        if not stat.S_ISREG(st.st_mode) or st.st_nlink!=1:raise RuntimeError('unsafe results file')
        old=RESULT.read_bytes()
        if not old.decode('utf8').startswith(MARKER):
            if not adopt_existing:raise RuntimeError('existing handwritten results require explicit preservation')
            fd=os.open(HISTORY,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
            with os.fdopen(fd,'wb') as f:
                f.write(old);f.flush();os.fchmod(f.fileno(),stat.S_IMODE(st.st_mode));os.fchown(f.fileno(),st.st_uid,st.st_gid);os.fsync(f.fileno())
    else:
        st=owner
    if HISTORY.is_file() and not HISTORY.is_symlink():
        text+='\n早期 M02 文字记录保留于 [历史记录](results-m02-history.md)。\n'
    fd,tmp=tempfile.mkstemp(prefix='.results-',dir=directory)
    try:
        with os.fdopen(fd,'w',encoding='utf8',newline='\n') as f:
            f.write(text);f.flush();os.fchmod(f.fileno(),0o644 if stat.S_ISDIR(st.st_mode) else stat.S_IMODE(st.st_mode));os.fchown(f.fileno(),st.st_uid,st.st_gid);os.fsync(f.fileno())
        os.replace(tmp,RESULT)
        dfd=os.open(directory,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
        try:os.fsync(dfd)
        finally:os.close(dfd)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--adopt-existing',action='store_true',help='preserve an older handwritten results page once')
    args=p.parse_args(argv)
    try:
        if os.geteuid()!=0:raise RuntimeError('root required to read protected events')
        write_result(render(),args.adopt_existing)
        print('Generated docs/results.md from protected events')
        return 0
    except (OSError,RuntimeError,UnicodeError,subprocess.SubprocessError) as exc:
        print('Results generation refused:',type(exc).__name__,file=sys.stderr)
        return 2


if __name__=='__main__':sys.exit(main())
